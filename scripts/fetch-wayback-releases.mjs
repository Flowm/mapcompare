#!/usr/bin/env node
/**
 * Generates src/lib/providers/waybackReleases.ts.
 *
 * Esri's World Imagery Wayback service addresses each dated snapshot by an OPAQUE INTEGER
 * release id, not by date:
 *
 *   .../WMTS/1.0.0/default028mm/MapServer/tile/{release}/{z}/{y}/{x}
 *
 * The date -> release mapping only exists in the service's WMTSCapabilities document, which
 * is ~225 kB of XML describing all 195 releases. Fetching that at runtime to populate a
 * dropdown would be absurd, so we resolve it once here and check the result in.
 *
 * Only one release per calendar year is kept (the latest in that year): 195 entries in a
 * picker is unusable, and a year-by-year time machine is what the comparison is actually for.
 *
 * Re-run with `pnpm run fetch-wayback` when a new year's imagery is worth adding.
 */
import { writeFileSync } from "node:fs";

const CAPABILITIES = "https://wayback.maptiles.arcgis.com/arcgis/rest/services/World_Imagery/WMTS/1.0.0/WMTSCapabilities.xml";
const OUT = new URL("../src/lib/providers/waybackReleases.ts", import.meta.url);

const res = await fetch(CAPABILITIES);
if (!res.ok) throw new Error(`Capabilities fetch failed: ${res.status} ${res.statusText}`);
const xml = await res.text();

// Each <Layer> holds an identifier (WB_2019_R08), a title carrying the capture date, and a
// ResourceURL template with the release id embedded in the path.
const releases = [];
for (const [, block] of xml.matchAll(/<Layer>([\s\S]*?)<\/Layer>/g)) {
  const identifier = /<ows:Identifier>(WB_\d{4}_R\d+)<\/ows:Identifier>/.exec(block)?.[1];
  const release = /template="[^"]*\/MapServer\/tile\/(\d+)\//.exec(block)?.[1];
  const date = /<ows:Title>[^<]*?\(Wayback (\d{4}-\d{2}-\d{2})\)/.exec(block)?.[1];
  if (identifier && release && date) releases.push({ identifier, release, date });
}

if (releases.length === 0) throw new Error("Parsed no releases — the capabilities format has changed");

// Latest release per calendar year, oldest year first.
const byYear = new Map();
for (const r of releases) {
  const year = r.date.slice(0, 4);
  const seen = byYear.get(year);
  if (!seen || r.date > seen.date) byYear.set(year, r);
}
const picked = [...byYear.values()].toSorted((a, b) => a.date.localeCompare(b.date));

const body = `// Generated by scripts/fetch-wayback-releases.mjs — do not edit by hand.
//
// Esri World Imagery Wayback addresses snapshots by an opaque integer release id, not by
// date. This is the date -> release mapping, one entry per calendar year (the latest release
// in each), resolved from the service's WMTSCapabilities document.
//
// Source: ${CAPABILITIES}
// ${releases.length} releases published in total; ${picked.length} kept.

import type { VariantValue } from "./types";

export const WAYBACK_RELEASES: readonly VariantValue[] = [
${picked.map((r) => `  { value: "${r.release}", label: "${r.date}" },`).join("\n")}
];

/** The newest kept snapshot — the default when a URL names no variant. */
export const WAYBACK_LATEST = "${picked.at(-1).release}";
`;

writeFileSync(OUT, body);
console.log(`Wrote ${picked.length} of ${releases.length} releases (${picked[0].date} .. ${picked.at(-1).date})`);
